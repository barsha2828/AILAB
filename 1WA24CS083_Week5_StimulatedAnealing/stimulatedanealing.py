import random
import math

def conflicts(board):
    n = len(board)
    count = 0
    for i in range(n):
        for j in range(i + 1, n):
            if board[i] == board[j] or abs(board[i] - board[j]) == j - i:
                count += 1
    return count

def simulated_annealing(n=8):
    board = [random.randrange(n) for _ in range(n)]
    cost = conflicts(board)

    for step in range(10000):
        if cost == 0:
            return board, step

        temperature = max(10 * (0.995 ** step), 1e-9)

        col = random.randrange(n)
        old_row = board[col]
        new_row = random.randrange(n)

        while new_row == old_row:
            new_row = random.randrange(n)

        board[col] = new_row
        new_cost = conflicts(board)
        delta = new_cost - cost

        if delta <= 0 or random.random() < math.exp(-delta / temperature):
            cost = new_cost
        else:
            board[col] = old_row

    return None, 10000

solution, steps = simulated_annealing()

if solution:
    print("Solution:", solution)
    print("Conflicting pairs:", conflicts(solution))
    print("Steps:", steps)
else:
    print("Solution not found.")



